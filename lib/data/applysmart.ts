function parseCourseInstitutionData(raw: string): Record<string, string[]> {
  const map: Record<string, string[]> = {};
  const entryRegex = /{[\s\S]*?"course"\s*:\s*"([^"]+)"[\s\S]*?"institutions"\s*:\s*\[([\s\S]*?)\][\s\S]*?}/g;
  let match: RegExpExecArray | null;

  while ((match = entryRegex.exec(raw)) !== null) {
    const course = match[1].trim();
    const institutionsText = match[2];
    const institutions: string[] = [];
    const institutionRegex = /"([^"]+)"/g;
    let institutionMatch: RegExpExecArray | null;

    while ((institutionMatch = institutionRegex.exec(institutionsText)) !== null) {
      institutions.push(institutionMatch[1].trim());
    }

    map[course] = institutions;
  }

  return map;
}


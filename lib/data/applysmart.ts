function inferFallbackInstitutionIds(course: string): string[] {
  const upperCourse = course.toUpperCase();

  if (/\b(SPORTS|PHYSICAL)\b/.test(upperCourse)) {
    return sportsFallbackInstitutionIds;
  }

  if (/\b(NURSING|DENTAL|MEDICAL|HEALTH|THERAPY|OPTICIANRY|ORTHOTICS|PROSTHETICS|EPIDEMIOLOGY)\b/.test(upperCourse)) {
    return healthFallbackInstitutionIds;
  }

  if (/\b(MARINE|NAUTICAL|SHIPPING|TRANSPORT|AVIATION|AUTO BODY|HIGHWAY)\b/.test(upperCourse)) {
    return transportFallbackInstitutionIds;
  }

  if (/\b(FILM|MULTI MEDIA|MULTIMEDIA|GRAPHICS|PHOTOGRAPHY|FASHION|CULTURAL|MUSIC)\b/.test(upperCourse)) {
    return creativeFallbackInstitutionIds;
  }

  if (/\b(AGRIC|FORESTRY|FISHERIES|HORTICULT|CROP|VETERINARY|WATER RESOURCES|HYDROLOGY|LEATHER)\b/.test(upperCourse)) {
    return agricultureFallbackInstitutionIds;
  }

  if (/\b(GEOLOGY|GEOGRAPHY|CARTOGRAPHY|CLIMATE|ENVIRONMENTAL|GEOSCIENCE|MINING)\b/.test(upperCourse)) {
    return earthScienceFallbackInstitutionIds;
  }

  if (/\b(COMPUTER|INFORMATION|SYSTEMS|COMMUNICATION|MEDIA)\b/.test(upperCourse)) {
    return computingFallbackInstitutionIds;
  }

  if (/\b(ACCOUNT|FINANCE|BUSINESS|MANAGEMENT|ADMINISTRATION|CRIME|INSURANCE|MARKETING|TAXATION)\b/.test(upperCourse)) {
    return businessFallbackInstitutionIds;
  }

  if (/\b(EDUCATION)\b/.test(upperCourse)) {
    return educationFallbackInstitutionIds;
  }

  if (/\b(ENGINEERING|TECHNOLOGY|ENERGY|GAS|WELDING|ELECTRICAL|ELECTRONICS)\b/.test(upperCourse)) {
    return technologyFallbackInstitutionIds;
  }

  return generalAcademicFallbackInstitutionIds;
}


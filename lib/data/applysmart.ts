function inferSupplementalHostState(id: string): string {
  const upperId = id.toUpperCase();
  const tokens = splitInstitutionCode(upperId);

  for (const token of [...tokens].reverse()) {
    if (locationStateHints[token]) {
      return locationStateHints[token];
    }
  }

  const joined = tokens.join(' ');
  for (const [token, state] of Object.entries(locationStateHints)) {
    if (joined.includes(token)) {
      return state;
    }
  }

  return 'Unknown';
}

